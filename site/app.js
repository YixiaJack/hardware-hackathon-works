  function pass(p, skip) {
    const f = S.f;
    if (f.q) { for (const w of f.q.split(/\s+/)) if (w && !p._t.includes(w)) return false; }
    for (const fid in f.fx) {
      if (fid === skip) continue;
      const sel = f.fx[fid];
      if (sel.size && !(p.f[fid] || []).some((x) => sel.has(x))) return false;
    }
    if (skip !== "series" && f.series.size && !f.series.has(p.sr)) return false;
    if (skip !== "years" && f.years.size && !f.years.has(p.y)) return false;
    if (skip !== "region" && f.region.size && !f.region.has(p._reg)) return false;
    if (f.winner && !p.w) return false;
    if (f.grand && p.w < 3) return false;
    if (f.video && !p.v) return false;
    if (f.repo && !p.r) return false;
    if (f.pick && !p.pk) return false;
    return true;
  }

