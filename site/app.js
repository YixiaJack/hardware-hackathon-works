    h += `<div class="group"><h3>${t("g_year")}</h3><div class="years">${years.map((y) => `<button class="tg" type="button" data-year="${y}" aria-pressed="${f.years.has(y)}">${y}<span style="opacity:.55"> ${cy.get(y)}</span></button>`).join("")}</div></div>`;
    const cr = counts("region", (p) => [p._reg]);
    const rItems = [...cr.entries()].map(([k, n]) => ({ v: k, n, label: esc(k) })).sort((a, b) => b.n - a.n);
    h += `<div class="group"><h3>${t("g_region")}</h3>${optList("region", rItems, f.region, 6)}</div>`;
    $("#rail").innerHTML = h;
