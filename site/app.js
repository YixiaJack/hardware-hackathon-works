    for (const fac of S.facets) {
      const c = counts(fac.id, (p) => p.f[fac.id] || []);
      const items = fac.terms.map((x) => ({ v: x.id, n: c.get(x.id) || 0, label: `${x.icon} ${esc(S.lang === "en" ? x.label_en : x.label)}` }))
        .filter((x) => x.n || f.fx[fac.id].has(x.v)).sort((a, b) => b.n - a.n);
      h += `<div class="group"><h3>${esc(facetLabel(fac))}<span>${esc(S.lang === "en" ? "" : fac.label_en)}</span></h3>${optList(fac.id, items, f.fx[fac.id], fac.id === "domain" ? 13 : 7)}</div>`;
    }
    const cs = counts("series", (p) => [p.sr]);
